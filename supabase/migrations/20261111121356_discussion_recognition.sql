create table private.discussion_recognitions (
  id uuid primary key,
  comment_id uuid not null references private.discussion_comments(id),
  awarded_creator_id uuid not null references public.creators(id),
  awarded_account_id uuid references public.profiles(id) on delete set null,
  reason text check (char_length(reason) between 1 and 240),
  awarded_at timestamptz not null default now(),
  revoked_at timestamptz,
  revoked_creator_id uuid references public.creators(id),
  revoked_account_id uuid references public.profiles(id) on delete set null
);
create unique index discussion_recognition_one_active on private.discussion_recognitions(comment_id) where revoked_at is null;
create index discussion_recognition_history on private.discussion_recognitions(comment_id,awarded_at desc);
alter table private.discussion_recognitions enable row level security;
revoke all on private.discussion_recognitions from public,anon,authenticated;

create function private.recognition_visible(c private.discussion_comments) returns boolean
language sql stable set search_path='' as $$
  select c.status='published' and (c.parent_comment_id is null or exists(
    select 1 from private.discussion_comments parent where parent.id=c.parent_comment_id and parent.status='published'))
$$;

create function private.recognition_recipient(c private.discussion_comments) returns uuid
language sql stable set search_path='' as $$
  select case when creator.owner_type='team' then
    case when private.announcement_owner(creator.id,private.discussion_owner(creator.id))
      then private.discussion_owner(creator.id) end
  else c.author_account_id end
  from (values(1)) placeholder(n) left join public.creators creator on creator.id=c.author_creator_id
$$;

create function private.recognition_is_self(c private.discussion_comments,p_creator uuid,p_account uuid) returns boolean
language sql stable set search_path='' as $$
  select p_account=c.author_account_id or p_account is not distinct from private.discussion_owner(c.author_creator_id)
    or p_creator is not distinct from c.author_creator_id
    or private.announcement_owner(p_creator,c.author_account_id)
$$;

create function public.discussion_recognition_state(p_mod uuid,p_comments uuid[]) returns jsonb
language sql stable security definer set search_path='' as $$
  with mod_access as (
    select private.announcement_creator(m.id,true,auth.uid()) awarding_creator
    from public.mods m where m.id=p_mod and private.follow_public_mod(m)
  ), comments as (
    select distinct id from unnest(p_comments[1:200]) as ids(id)
  )
  select coalesce(jsonb_object_agg(c.id,jsonb_build_object(
    'active',r.id is not null and private.recognition_visible(c),
    'reason',case when private.recognition_visible(c) then r.reason end,
    'canAward',mod_access.awarding_creator is not null and r.id is null and private.recognition_visible(c)
      and not private.recognition_is_self(c,mod_access.awarding_creator,auth.uid()),
    'canRevoke',mod_access.awarding_creator is not null and r.id is not null,
    'recognitionId',case when mod_access.awarding_creator is not null then r.id end
  )),'{}'::jsonb)
  from comments join private.discussion_comments c on c.id=comments.id
  cross join mod_access
  left join private.discussion_recognitions r on r.comment_id=c.id and r.revoked_at is null
  where c.target_type='mod' and c.target_id=p_mod
    and (private.recognition_visible(c) or mod_access.awarding_creator is not null)
$$;

create function private.guard_recognition_activity() returns trigger
language plpgsql set search_path='' as $$
begin
  if current_user not in ('postgres','supabase_admin') and
    (new.event_type='discussion_recognized' or (tg_op='UPDATE' and old.event_type='discussion_recognized')) then
    raise exception 'Recognition activity must be generated by an award.' using errcode='42501';
  end if;
  return new;
end $$;
create trigger guard_recognition_activity before insert or update on public.activity_events
for each row execute function private.guard_recognition_activity();

create function public.write_discussion_recognition(p_mod uuid,p_comment uuid,p_action text,p_request uuid,p_reason text default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  account uuid := auth.uid();
  awarded_by uuid;
  recipient uuid;
  c private.discussion_comments;
  m public.mods;
  event_id uuid;
  saved uuid;
  reason text := nullif(btrim(p_reason),'');
begin
  if account is null then raise exception 'Sign in to manage recognition.' using errcode='42501'; end if;
  if p_action is null or p_action not in ('award','revoke') or p_request is null or char_length(reason)>240 then
    raise exception 'Invalid recognition request.' using errcode='22023';
  end if;
  select * into c from private.discussion_comments
    where id=p_comment and target_type='mod' and target_id=p_mod for update;
  if not found then raise exception 'Discussion unavailable.' using errcode='42501'; end if;
  select * into m from public.mods where id=p_mod and private.follow_public_mod(mods) for share;
  if not found then raise exception 'Mod unavailable.' using errcode='42501'; end if;
  awarded_by := private.announcement_creator(m.id,true,account);
  if awarded_by is null then raise exception 'Only a verified mod owner can manage recognition.' using errcode='42501'; end if;
  if m.creator_id is not null and m.creator_id<>awarded_by then perform private.require_operational_creator(m.creator_id); end if;
  perform private.require_operational_creator(awarded_by);

  if p_action='revoke' then
    update private.discussion_recognitions set revoked_at=now(),revoked_creator_id=awarded_by,revoked_account_id=account
      where id=p_request and comment_id=c.id and revoked_at is null;
  elsif not exists(select 1 from private.discussion_recognitions
      where id=p_request and comment_id=c.id and awarded_account_id=account) then
    if c.parent_comment_id is not null then
      perform 1 from private.discussion_comments where id=c.parent_comment_id for share;
    end if;
    if not private.recognition_visible(c) then raise exception 'Only public contributions can be recognized.' using errcode='42501'; end if;
    if private.recognition_is_self(c,awarded_by,account) then
      raise exception 'You cannot recognize your own contribution.' using errcode='42501';
    end if;
    insert into private.discussion_recognitions(id,comment_id,awarded_creator_id,awarded_account_id,reason)
      values(p_request,c.id,awarded_by,account,reason)
      on conflict do nothing returning id into saved;
    if saved is null and not exists(select 1 from private.discussion_recognitions where comment_id=c.id and revoked_at is null) then
      raise exception 'Recognition request identifier is unavailable.' using errcode='23505';
    end if;
    recipient := private.recognition_recipient(c);
    if saved is not null and recipient is distinct from account and exists(select 1 from public.profiles where id=recipient) then
      insert into public.activity_events(event_type,actor_type,actor_id,target_type,target_id,parent_type,parent_id,visibility,title,summary,metadata)
      values('discussion_recognized','creator',awarded_by,'comment',c.id,'mod',m.id,'private','Helpful contribution recognized',
        (select name from public.creators where id=awarded_by) || ' recognized your helpful contribution to ' || m.title || '.',
        jsonb_build_object('discussionCommentId',c.id,'modId',m.id))
      returning id into event_id;
      insert into public.notifications(profile_id,activity_event_id) values(recipient,event_id);
    end if;
  end if;
  return public.discussion_recognition_state(p_mod,array[c.id])->c.id::text;
end $$;

create function public.community_contributions(p_kind text,p_identity uuid) returns jsonb
language sql stable security definer set search_path='' as $$
  with visible as (
    select c.id,c.target_id,m.title mod_title,c.body,r.awarded_at,r.awarded_creator_id,creator.name creator_name
    from private.discussion_comments c
    join private.discussion_recognitions r on r.comment_id=c.id and r.revoked_at is null
    join public.mods m on c.target_type='mod' and m.id=c.target_id and private.follow_public_mod(m)
    join public.creators creator on creator.id=r.awarded_creator_id
    where ((p_kind='user' and c.author_creator_id is null and c.author_account_id=p_identity)
      or (p_kind='creator' and c.author_creator_id=p_identity)) and private.recognition_visible(c)
  )
  select jsonb_build_object('count',(select count(*) from visible),
    'creators',(select count(distinct awarded_creator_id) from visible),
    'recent',coalesce((select jsonb_agg(jsonb_build_object(
      'id',id,'target_id',target_id,'modTitle',mod_title,'excerpt',left(body,180),'creatorName',creator_name)
      order by awarded_at desc,id) from (select * from visible order by awarded_at desc,id limit 3) recent),'[]'::jsonb))
$$;

revoke all on function private.recognition_visible(private.discussion_comments),private.recognition_recipient(private.discussion_comments),
  private.recognition_is_self(private.discussion_comments,uuid,uuid),private.guard_recognition_activity() from public,anon,authenticated;
revoke all on function public.discussion_recognition_state(uuid,uuid[]),public.write_discussion_recognition(uuid,uuid,text,uuid,text),
  public.community_contributions(text,uuid) from public,anon,authenticated;
grant execute on function public.discussion_recognition_state(uuid,uuid[]),public.community_contributions(text,uuid) to anon,authenticated;
grant execute on function public.write_discussion_recognition(uuid,uuid,text,uuid,text) to authenticated;
notify pgrst, 'reload schema';
